// @ts-check

/* Compile panel.scss and embed the result as globalThis.kraftyPanelCss for
   injection into each panel's shadow root (item 24).

   Pass --check to exit 1 when panelCss.js would change, without writing.
   pretest runs that first so a stale commit fails before build overwrites it. */

const fs = require("node:fs");
const path = require("node:path");
const sass = require("sass");

const root = path.join(__dirname, "..");
const scss = path.join(root, "code", "panel.scss");
const cssPath = path.join(root, "code", "panel.css");
const out = path.join(root, "code", "js", "panelCss.js");
const check = process.argv.includes("--check");

const result = sass.compile(scss, { style: "compressed" });
const source = [
  "// @ts-check",
  "/* Generated by scripts/embed-panel-css.js — do not edit. */",
  `globalThis.kraftyPanelCss = ${JSON.stringify(result.css)};`,
  "",
].join("\n");

if (check) {
  const current = fs.existsSync(out) ? fs.readFileSync(out, "utf8") : "";

  if (current !== source) {
    console.error(
      "code/js/panelCss.js is out of date with panel.scss — run npm run build"
    );
    process.exit(1);
  }

  console.log(`Checked ${path.relative(root, out)}`);
  process.exit(0);
}

fs.writeFileSync(cssPath, result.css);
fs.writeFileSync(out, source);
console.log(`Embedded ${path.relative(root, out)}`);
